/**
 * Closing a market with as many orders resting as it can hold: 200,000, twenty for each of 10,000 accounts on five
 * instruments, which is the limit per account times the largest bot population. The market is generated by SQL as
 * the database's owner, with every order's hold and its ledger batch, so that the engine's own startup rebuilds the
 * books from it and reconciles it before the close is timed. The close then runs through the real engine and store
 * against PostgreSQL in Testcontainers, once for each part size given, each on a market of its own.
 *
 * <p>
 * Testcontainers runs PostgreSQL with fsync off unless {@code -Dmse.test.fsync=on} is given; the report says which.
 *
 * <p>
 * Not part of the build; run it on its own:
 * {@code mvnw -pl services/execution-service verify -Dtest=None -Dsurefire.failIfNoSpecifiedTests=false
 * -Dit.test=MarketCloseBench}, with {@code -Dmse.bench.close.orders=} and {@code -Dmse.bench.close.chunks=} for other
 * sizes. It writes {@code target/market-close-<time>.txt}.
 */
@Import(TestcontainersConfiguration.class)
@SpringBootTest(properties = "mse.test.database=market-close-bench")
class MarketCloseBench {

	private static final int ORDERS_PER_ACCOUNT = 20;

	private static final int INSTRUMENTS = 5;

	@Autowired
	JdbcTemplate jdbc;

	@Autowired
	DataSource dataSource;

	@Autowired
	PlatformTransactionManager transactionManager;

	@Autowired
	PostgreSQLContainer postgres;

	/** Each transaction of a close as the engine timed it: opening, statements and commit, in nanoseconds. */
	private static final class CloseTimes implements WriterTimings {

		final List<long[]> transactions = new ArrayList<>();

		long applying;

		private long[] current;

		@Override
		public void record(Phase phase, String command, long nanos) {
			if (!"close".equals(command)) {
				return;
			}
			switch (phase) {
				case BEGIN -> current = new long[] { nanos, 0, 0 };
				case WORK -> current[1] = nanos;
				case COMMIT -> {
					current[2] = nanos;
					transactions.add(current);
				}
				case APPLY -> applying += nanos;
				default -> {
				}
			}
		}

		@Override
		public void runFellBack(int commands) {
		}

	}

	@Test
	void close() throws Exception {
		int orders = Integer.getInteger("mse.bench.close.orders", 200_000);
		String[] chunks = System.getProperty("mse.bench.close.chunks", "5000").split(",");
		TradingStore store = new JdbcTradingStore(JdbcClient.create(dataSource), JsonMapper.builder().build());
		UUID operator = UUID.randomUUID();
		TestUsers.insert(jdbc, operator, "bench.closer", TestBrowser.passwordHash("test-bench-password"), "OPERATOR");
		StringBuilder report = new StringBuilder();
		report.append(String.format(Locale.ROOT, "PostgreSQL: fsync=%s, synchronous_commit=%s, shared_buffers=%s%n%n",
				setting("fsync"), setting("synchronous_commit"), setting("shared_buffers")));
		for (String chunk : chunks) {
			report.append(closeOne(store, operator, orders, Integer.parseInt(chunk.strip()))).append('\n');
		}
		System.out.println(report);
		Files.writeString(Path.of("target", "market-close-" + Instant.now().toString().replace(':', '-') + ".txt"),
				report);
	}

	private String closeOne(TradingStore store, UUID operator, int orders, int chunk) throws Exception {
		long began = System.nanoTime();
		UUID simulation = generate(orders);
		long generated = System.nanoTime();
		CommandWriter writer = new CommandWriter("bench-writer", 16);
		CloseTimes times = new CloseTimes();
		try {
			TradingEngine engine = new TradingEngine(store, new SpringTransactionRunner(transactionManager), writer,
					Clock.systemUTC(), (account) -> {
						throw new UnsupportedOperationException("no bots are made here");
					}, AccountChanges.NONE, times, System::nanoTime, new RestingOrders(), chunk);
			engine.start();
			long started = System.nanoTime();
			MarketClosing closed = engine
				.close(new CommandKey(operator, UUID.randomUUID(), "POST /api/v1/admin/market/close", new byte[32]),
						new MarketControl(MarketControl.Action.CLOSE, operator))
				.get(30, TimeUnit.MINUTES);
			long done = System.nanoTime();

			assertThat(closed.canceledOrders()).isEqualTo(orders);
			assertThat(jdbc.queryForObject("""
					SELECT count(*) FROM orders WHERE simulation_id = ? AND state = 'CANCELED' AND reason = 'MARKET_CLOSED'""",
					Long.class, simulation)).isEqualTo(orders);
			assertThat(jdbc.queryForObject("""
					SELECT (SELECT coalesce(sum(b.reserved_cents), 0) FROM cash_balance b JOIN account a ON a.id = b.account_id
					        WHERE a.simulation_id = ?)
					    + (SELECT coalesce(sum(p.reserved_quantity), 0) FROM position p JOIN account a ON a.id = p.account_id
					        WHERE a.simulation_id = ?)""", Long.class, simulation, simulation)).as("holds left").isZero();
			long reconciling = System.nanoTime();
			List<String> problems = new TransactionTemplate(transactionManager)
				.execute((status) -> store.reconciliationProblems(simulation));
			long reconciled = System.nanoTime();
			assertThat(problems).isEmpty();

			long[] longest = times.transactions.stream()
				.max((a, b) -> Long.compare(a[0] + a[1] + a[2], b[0] + b[1] + b[2]))
				.orElseThrow();
			long[] sorted = times.transactions.stream().mapToLong((t) -> t[0] + t[1] + t[2]).sorted().toArray();
			return String.format(Locale.ROOT, """
					%,d resting orders of %,d accounts on %d instruments, %,d per transaction
					  generated in %,d ms; startup (books rebuilt, reconciled) %,d ms
					  close: %,d transactions, %,d ms in all
					  longest transaction %,d ms (statements %,d ms, commit %,d ms); median %,d ms
					  applying to the books %,d ms in all; reconciliation afterwards %,d ms
					""", orders, orders / ORDERS_PER_ACCOUNT, INSTRUMENTS, chunk, millis(generated - began),
					millis(started - generated), times.transactions.size(), millis(done - started),
					millis(longest[0] + longest[1] + longest[2]), millis(longest[1]), millis(longest[2]),
					millis(sorted[sorted.length / 2]), millis(times.applying), millis(reconciled - reconciling));
		}
		finally {
			writer.close(Duration.ofSeconds(5));
		}
	}

	/**
	 * An open market beside whatever closed ones there are, with {@code orders} orders resting and nothing else: ten
	 * bids below 99.00 and ten offers above 101.00 for each account, two of each on every instrument, so no book is
	 * crossed. Each order has what the writer would have left for it: its hold in the balance, and a RESERVE batch that
	 * moves it from available to reserved.
	 */
	private UUID generate(int orders) throws Exception {
		UUID simulation = UUID.randomUUID();
		int accounts = orders / ORDERS_PER_ACCOUNT;
		try (Connection owner = DriverManager.getConnection(TestcontainersConfiguration.jdbcUrl(postgres, "execution_db"),
				"execution_owner", TestcontainersConfiguration.EXECUTION_OWNER_PASSWORD);
				Statement statement = owner.createStatement()) {
			owner.setAutoCommit(false);
			for (String sql : GENERATE.formatted(simulation, accounts, INSTRUMENTS, ORDERS_PER_ACCOUNT).split(";\\s*\n")) {
				if (!sql.isBlank()) {
					statement.execute(sql);
				}
			}
			owner.commit();
			owner.setAutoCommit(true);
			statement.execute("ANALYZE simulation, account, instrument, cash_balance, position, orders, journal_batch, ledger_entry");
		}
		return simulation;
	}

	/** Arguments: the simulation, the number of accounts, of instruments, and of orders for each account. */
	private static final String GENERATE = """
			ALTER TABLE ledger_entry DISABLE TRIGGER ledger_entry_balanced;
			UPDATE simulation SET state = 'CLOSED', closed_at = now() WHERE state <> 'CLOSED';
			INSERT INTO simulation (id, state, opened_at, last_command_sequence)
			    VALUES ('%1$s', 'OPEN', now(), %2$d * %4$d);
			CREATE TEMP TABLE bench_instrument ON COMMIT DROP AS
			    SELECT gen_random_uuid() AS id, i FROM generate_series(0, %3$d - 1) i;
			CREATE TEMP TABLE bench_account ON COMMIT DROP AS
			    SELECT gen_random_uuid() AS id, n FROM generate_series(1, %2$d) n;
			CREATE TEMP TABLE bench_order ON COMMIT DROP AS
			    SELECT gen_random_uuid() AS id, a.id AS account_id, i.id AS instrument_id,
			        CASE WHEN k < %4$d / 2 THEN 'BUY' ELSE 'SELL' END AS side,
			        CASE WHEN k < %4$d / 2 THEN 9000 ELSE 10100 END + (a.n * 7 + k * 13) %% 900 AS price,
			        1 + (a.n + k) %% 10 AS quantity, (a.n - 1) * %4$d + k + 1 AS sequence
			    FROM bench_account a CROSS JOIN generate_series(0, %4$d - 1) k
			    JOIN bench_instrument i ON i.i = k %% %3$d;
			INSERT INTO account (id, simulation_id, kind, display_name)
			    VALUES (gen_random_uuid(), '%1$s', 'ISSUANCE', 'Issuance');
			INSERT INTO account (id, simulation_id, kind, display_name, bot_strategy)
			    SELECT id, '%1$s', 'BOT', 'bot-' || n, 'NOISE' FROM bench_account;
			INSERT INTO instrument (id, simulation_id, symbol, reference_price_cents)
			    SELECT id, '%1$s', 'BN' || chr(65 + i), 10000 FROM bench_instrument;
			INSERT INTO orders (id, simulation_id, account_id, instrument_id, side, type, time_in_force, bound_cents,
			        requested_quantity, filled_quantity, working_quantity, state, accepted_sequence)
			    SELECT id, '%1$s', account_id, instrument_id, side, 'LIMIT', 'GTC', price, quantity, 0, quantity, 'OPEN',
			        sequence FROM bench_order;
			INSERT INTO cash_balance (account_id, account_kind, total_cents, reserved_cents)
			    SELECT account_id, 'BOT', 100000000, sum(price * quantity) FROM bench_order WHERE side = 'BUY'
			    GROUP BY account_id;
			INSERT INTO position (account_id, account_kind, instrument_id, total_quantity, reserved_quantity)
			    SELECT a.id, 'BOT', i.id, 10000, coalesce(held.quantity, 0)
			    FROM bench_account a CROSS JOIN bench_instrument i
			    LEFT JOIN (SELECT account_id, instrument_id, sum(quantity) AS quantity FROM bench_order
			        WHERE side = 'SELL' GROUP BY 1, 2) held ON held.account_id = a.id AND held.instrument_id = i.id;
			INSERT INTO journal_batch (id, simulation_id, cause, command_sequence)
			    SELECT md5('genesis' || id)::uuid, '%1$s', 'GENESIS', 1 FROM bench_account;
			INSERT INTO ledger_entry (batch_id, account_id, instrument_id, bucket, delta)
			    SELECT md5('genesis' || a.id)::uuid, who.id, asset.id, 'AVAILABLE', who.sign * asset.amount
			    FROM bench_account a
			    CROSS JOIN (SELECT NULL::uuid AS id, 100000000 AS amount UNION ALL SELECT id, 10000 FROM bench_instrument)
			        asset
			    CROSS JOIN LATERAL (VALUES (a.id, 1), ((SELECT id FROM account WHERE simulation_id = '%1$s'
			        AND kind = 'ISSUANCE'), -1)) AS who(id, sign);
			INSERT INTO journal_batch (id, simulation_id, cause, command_sequence)
			    SELECT md5('reserve' || id)::uuid, '%1$s', 'RESERVE', sequence FROM bench_order;
			INSERT INTO ledger_entry (batch_id, account_id, instrument_id, bucket, delta)
			    SELECT md5('reserve' || o.id)::uuid, o.account_id,
			        CASE WHEN o.side = 'SELL' THEN o.instrument_id END, bucket.name,
			        bucket.sign * CASE WHEN o.side = 'BUY' THEN o.price * o.quantity ELSE o.quantity END
			    FROM bench_order o CROSS JOIN (VALUES ('AVAILABLE', -1), ('RESERVED', 1)) AS bucket(name, sign);
			ALTER TABLE ledger_entry ENABLE TRIGGER ledger_entry_balanced;
			""";

	private String setting(String name) {
		return jdbc.queryForObject("SELECT current_setting(?)", String.class, name);
	}

	private static long millis(long nanos) {
		return nanos / 1_000_000;
	}

}
